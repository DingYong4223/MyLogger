from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json
url=Path('design/adb-workbench/index.html').resolve().as_uri()
report={'checks':[], 'layouts':[]}
with sync_playwright() as p:
    browser=p.chromium.launch()
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[]
    page.on('pageerror',lambda err:errors.append(str(err)))
    page.goto(url)
    def check(label):
        assert not errors,errors
        report['checks'].append(label)
    def nav(name):
        page.locator('#navigation [data-nav="'+name+'"]').click()
        if name=='schema':
            expect(page.locator('#modal')).to_be_visible()
            page.locator('#confirm-device').click()
    def no_overflow():
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),page.evaluate('({w:innerWidth,sw:document.documentElement.scrollWidth})')
    for name in ['home','devices','apps','schema','logs','media','files','network','diagnostics','workflows','favorites','history','tasks']:
        nav(name)
        expect(page.locator('h1')).to_be_visible()
        no_overflow()
    check('13 modules render without page overflow')
    nav('home')
    page.evaluate('window.originalMain=document.querySelector("main"); window.originalContent=originalMain.firstElementChild;')
    page.locator('#device-context').click()
    page.keyboard.press('Escape')
    assert page.evaluate('originalMain.isConnected && originalContent.isConnected && originalMain===document.querySelector("main")')
    check('Closing overlay preserves background DOM')
    page.locator('[data-action="schema"]').first.click()
    expect(page.locator('#modal-title')).to_have_text('选择目标设备')
    expect(page.locator('#schema-uri')).to_have_count(0)
    page.keyboard.press('ArrowDown')
    page.keyboard.press('Enter')
    expect(page.locator('#device-label')).to_have_text('Pixel 7 · 模拟器')
    uri='demo://product?name=中文&value='+('abcdefghij'*70)
    field=page.locator('#schema-uri')
    field.fill(uri);field.press('End')
    assert field.evaluate('(e)=>e.scrollLeft > 0')
    page.locator('#schema-form [type="submit"]').click()
    expect(page.locator('.result-output').first).to_contain_text('Status: ok')
    expect(page.locator('.result-meta').first).to_contain_text('emulator-5554')
    dock=page.locator('#command-input')
    dock.focus();dock.press('ArrowUp')
    expect(dock).to_have_value(uri)
    expect(page.locator('#command-mode')).to_contain_text('SCHEMA')
    dock.press('ArrowDown');expect(dock).to_have_value('')
    field=page.locator('#schema-uri');field.fill('demo://草稿');field.press('ArrowUp');expect(field).to_have_value(uri)
    field.press('ArrowDown');expect(field).to_have_value('demo://草稿')
    field.fill('unhandled://missing');page.locator('#schema-form [type="submit"]').click()
    expect(page.locator('.result-output').first).to_contain_text('unable to resolve')
    expect(page.locator('.result-meta .tag').first).to_have_text('失败')
    check('Multi-device gating, long URI scrolling, history, draft and failure results')
    page.locator('[data-action="save-favorite"]').click()
    page.locator('#favorite-name').fill('测试收藏')
    page.locator('#favorite-uri').fill('demo://saved')
    page.locator('#favorite-form [type="submit"]').click()
    nav('favorites');expect(page.get_by_text('测试收藏',exact=True)).to_be_visible()
    page.locator('[data-favorite="3"]').click();page.locator('#confirm-device').click()
    expect(page.locator('#schema-uri')).to_have_value('demo://saved')
    check('Favorites save and restore for editing')
    page.locator('[data-action="intent"]').click()
    page.locator('#intent-kind').select_option('broadcast')
    page.locator('#intent-extra').fill('source=debug')
    page.locator('#intent-form .primary').click()
    expect(page.locator('.result-output').first).to_contain_text('Status: ok')
    nav('apps');page.locator('#app-filter').fill('staging')
    expect(page.locator('#app-rows tr')).to_have_count(1)
    page.locator('#app-filter').fill('')
    page.locator('[data-action="permissions"]').click()
    expect(page.locator('#permissions-form input[type=checkbox]')).to_have_count(3)
    page.locator('#permissions-form .primary').click()
    page.locator('[data-action="clear-data"]').click()
    expect(page.locator('#modal-content')).to_contain_text('无法撤销')
    page.locator('#modal [data-close]').click()
    page.locator('[data-action="install"]').click();page.locator('#confirm-device').click()
    page.locator('#install-form .primary').click()
    expect(page.locator('#toast')).to_contain_text('安装 APK已完成')
    check('Intent, app search, permission form, destructive confirmation and install')
    nav('logs');page.locator('#log-level').select_option('E')
    expect(page.locator('.log-row')).to_have_count(3)
    page.locator('#log-query').fill('bind')
    expect(page.locator('.log-row')).to_have_count(1)
    page.locator('[data-action="pause-log"]').click()
    expect(page.locator('.coverage')).to_contain_text('滚动已暂停')
    check('Log filtering and scroll state')
    nav('media');page.locator('[data-action="record"]').click();page.locator('#confirm-device').click()
    expect(page.get_by_text('■ 停止并保存录屏',exact=True)).to_be_visible()
    page.get_by_text('■ 停止并保存录屏',exact=True).click()
    nav('tasks')
    expect(page.locator('[data-stop]').filter(has_text='停止并保存')).to_have_count(1)
    expect(page.get_by_text('设备录屏',exact=False).first).to_be_visible()
    page.locator('[data-artifact]').first.click()
    expect(page.locator('#modal-title')).to_have_text('产物详情');page.locator('#modal [data-close]').click()
    check('Recording stop/save and artifacts')
    nav('network');page.locator('[data-action="add-mapping"]').click()
    page.locator('#device-port').fill('9080');page.locator('#host-port').fill('8080')
    page.locator('#mapping-form .primary').click()
    expect(page.get_by_text('tcp:9080',exact=True)).to_be_visible()
    page.locator('[data-remove-mapping]').click()
    expect(page.get_by_text('当前设备没有端口映射。',exact=True)).to_be_visible()
    check('Port mapping create and scoped deletion')
    nav('devices');page.locator('#connection-scenario').select_option('none')
    expect(page.locator('#device-label')).to_have_text('未连接设备')
    page.locator('#navigation [data-nav="schema"]').click()
    expect(page.locator('#modal-title')).to_have_text('没有可用设备')
    page.locator('#modal [data-close]').click()
    page.locator('#connection-scenario').select_option('single')
    page.locator('#navigation [data-nav="schema"]').click()
    expect(page.locator('#modal')).not_to_be_visible();expect(page.locator('#schema-uri')).to_be_visible()
    check('Zero-device error and single-device direct entry')
    page.locator('#search-launch').click();page.locator('#palette-input').fill('schema')
    expect(page.locator('.palette-item')).to_have_count(1)
    page.keyboard.press('Enter');expect(page.locator('#schema-uri')).to_be_visible()
    page.locator('#search-launch').click();page.locator('#palette-input').fill('no-such-action')
    expect(page.locator('#palette-results')).to_contain_text('没有匹配的操作')
    page.keyboard.press('Escape')
    check('Search palette keyboard execution and empty state')
    for size in [(1440,1000),(1280,800),(900,800),(390,844)]:
        page.set_viewport_size({'width':size[0],'height':size[1]})
        for name in ['home','schema','logs','network','tasks']:
            if name=='schema':page.locator('#navigation [data-nav="schema"]').click()
            else:nav(name)
            no_overflow()
            expect(page.locator('h1')).to_be_visible()
        geometry=page.locator('.command-dock').bounding_box()
        assert geometry['width']>0 and geometry['x']>=0
        assert page.locator('.panel').first.evaluate('(el)=>getComputedStyle(el).borderRadius')=='6px'
        report['layouts'].append({'viewport':size,'dock':geometry})
    check('Desktop, narrow window and mobile layout / 6px panel corners')
    assert not errors,errors
    report['errors']=errors
    Path('tmp/adb-workbench-checks.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
    browser.close()
print(json.dumps({'passed':len(report['checks']),'layouts':len(report['layouts']),'errors':report['errors']},ensure_ascii=False))
